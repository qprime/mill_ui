from __future__ import annotations

import os
import re
from collections.abc import Iterator, Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from ruamel.yaml import YAML

from validation.recipes import OUTPUT_DIR_NAME, RECIPES_ROOT, Recipe

CATALOG_NAME = "catalog.yml"
README_NAME = "README.md"
FEATURE_GUIDE_NAME = "feature_guide.md"
THUMBNAIL_WIDTH = 240
DEMONSTRATES_PREFIX = "**Demonstrates:**"
REGEN_NOTE = "Generated by `python -m cli.recipes --regen`. Do not edit by hand."
MARKDOWN_IMAGE = re.compile(r"!\[[^\]]*\]\(([^)\s]+)")


@dataclass(frozen=True)
class Category:
    key: str
    title: str
    description: str


@dataclass(frozen=True)
class DetectRule:
    kind: str
    target: str = ""
    value: Any = None
    recipes: tuple[str, ...] = ()


@dataclass(frozen=True)
class Capability:
    name: str
    summary: str
    spec: str
    detect: tuple[DetectRule, ...]


@dataclass(frozen=True)
class GuideGroup:
    name: str
    capabilities: tuple[Capability, ...]


@dataclass(frozen=True)
class Catalog:
    categories: tuple[Category, ...]
    guide: tuple[GuideGroup, ...]


@dataclass(frozen=True)
class RecipeReadme:
    title: str | None
    demonstrates: str | None
    images: tuple[str, ...]


def feature_guide_path(root: Path = RECIPES_ROOT) -> Path:
    return root.parent / FEATURE_GUIDE_NAME


def _load_yaml(path: Path) -> Any:
    return YAML(typ="safe", pure=True).load(path.read_text(encoding="utf-8"))


def parse_detect_rule(raw: Any) -> DetectRule:
    if isinstance(raw, Mapping) and len(raw) == 1:
        ((kind, arg),) = raw.items()
        if kind in ("node", "param") and isinstance(arg, str):
            return DetectRule(kind=kind, target=arg)
        if kind == "value" and isinstance(arg, Mapping) and len(arg) == 1:
            ((key, value),) = arg.items()
            return DetectRule(kind=kind, target=str(key), value=value)
        if kind == "recipes" and isinstance(arg, list) and all(isinstance(name, str) for name in arg):
            return DetectRule(kind=kind, recipes=tuple(arg))
    raise ValueError(
        f"Malformed detect rule {raw!r}: expected {{node: Type}}, {{param: key}}, {{value: {{key: scalar}}}} "
        "or {recipes: [name, ...]}"
    )


def _parse_capability(raw: Mapping[str, Any]) -> Capability:
    detect = raw.get("detect", [])
    if not isinstance(detect, list):
        raise ValueError(f"Capability '{raw['name']}': detect must be a list of rules")
    return Capability(
        name=raw["name"],
        summary=raw["summary"],
        spec=raw["spec"],
        detect=tuple(parse_detect_rule(rule) for rule in detect),
    )


def load_catalog(root: Path = RECIPES_ROOT) -> Catalog:
    data = _load_yaml(root / CATALOG_NAME)
    categories = tuple(
        Category(key=str(key), title=entry["title"], description=entry["description"])
        for key, entry in data["categories"].items()
    )
    guide = tuple(
        GuideGroup(name=group["group"], capabilities=tuple(_parse_capability(raw) for raw in group["capabilities"]))
        for group in data["guide"]
    )
    return Catalog(categories=categories, guide=guide)


def _entries(node: Any) -> Iterator[tuple[Any, Any]]:
    if isinstance(node, Mapping):
        for key, value in node.items():
            yield key, value
            yield from _entries(value)
    elif isinstance(node, list):
        for item in node:
            yield from _entries(item)


def _holds(value: Any, wanted: Any) -> bool:
    return bool(value == wanted or (isinstance(value, list) and wanted in value))


def rule_matches(rule: DetectRule, recipe_name: str, documents: Sequence[Any]) -> bool:
    if rule.kind == "recipes":
        return recipe_name in rule.recipes
    entries = [entry for document in documents for entry in _entries(document)]
    if rule.kind == "value":
        return any(key == rule.target and _holds(value, rule.value) for key, value in entries)
    return any(key == rule.target for key, _ in entries)


def capability_matches(capability: Capability, recipe_name: str, documents: Sequence[Any]) -> bool:
    return any(rule_matches(rule, recipe_name, documents) for rule in capability.detect)


def recipe_documents(recipe: Recipe) -> tuple[Any, ...]:
    return tuple(_load_yaml(source) for source in (*recipe.pml_sources, *recipe.nest_sources))


def read_readme(recipe: Recipe) -> RecipeReadme | None:
    path = recipe.path / README_NAME
    if not path.is_file():
        return None
    text = path.read_text(encoding="utf-8")
    lines = text.splitlines()
    return RecipeReadme(
        title=next((line[2:].strip() for line in lines if line.startswith("# ")), None),
        demonstrates=next(
            (line.removeprefix(DEMONSTRATES_PREFIX).strip() for line in lines if line.startswith(DEMONSTRATES_PREFIX)),
            None,
        ),
        images=tuple(MARKDOWN_IMAGE.findall(text)),
    )


def readme_problems(recipe: Recipe) -> list[str]:
    readme = read_readme(recipe)
    if readme is None:
        return [f"no {README_NAME}"]
    problems = []
    if readme.title is None:
        problems.append(f"{README_NAME} has no '# ' title")
    if readme.demonstrates is None:
        problems.append(f"{README_NAME} has no {DEMONSTRATES_PREFIX} line")
    own_outputs = [image for image in readme.images if image.startswith(f"{OUTPUT_DIR_NAME}/")]
    if not any((recipe.path / image).is_file() for image in own_outputs):
        problems.append(f"{README_NAME} embeds no image from its own {OUTPUT_DIR_NAME}/ that exists")
    return problems


def uncatalogued_categories(catalog: Catalog, recipes: Sequence[Recipe]) -> list[str]:
    keys = {category.key for category in catalog.categories}
    return [
        f"{recipe.name}: category '{recipe.category}' is not listed in {CATALOG_NAME}"
        for recipe in recipes
        if recipe.category not in keys
    ]


def unknown_recipe_names(catalog: Catalog, recipes: Sequence[Recipe]) -> list[str]:
    names = {recipe.name for recipe in recipes}
    return [
        f"{CATALOG_NAME}: capability '{capability.name}' names recipe '{name}', which does not exist"
        for group in catalog.guide
        for capability in group.capabilities
        for rule in capability.detect
        for name in rule.recipes
        if name not in names
    ]


def _relative_link(target: Path, from_dir: Path) -> str:
    return Path(os.path.relpath(target, from_dir)).as_posix()


def _recipe_entry(recipe: Recipe, readme: RecipeReadme | None, from_dir: Path, heading: str) -> list[str]:
    link = f"{_relative_link(recipe.path, from_dir)}/"
    title = readme.title if readme is not None and readme.title else recipe.name
    lines = [f"{heading} [{title}]({link})", ""]
    if readme is not None and readme.images:
        lines += [f'<img src="{link}{readme.images[0]}" width="{THUMBNAIL_WIDTH}">', ""]
    if readme is not None and readme.demonstrates:
        lines += [readme.demonstrates, ""]
    return lines


def _members(category: Category, recipes: Sequence[Recipe]) -> list[Recipe]:
    return sorted((recipe for recipe in recipes if recipe.category == category.key), key=lambda recipe: recipe.name)


def render_index(
    catalog: Catalog, recipes: Sequence[Recipe], readmes: Mapping[str, RecipeReadme | None], root: Path
) -> str:
    guide_link = _relative_link(feature_guide_path(root), root)
    lines = ["# Recipes", "", REGEN_NOTE, "", f"See the [feature guide]({guide_link}) for every PML capability.", ""]
    for category in catalog.categories:
        lines += [f"## {category.title}", "", category.description, ""]
        members = _members(category, recipes)
        if not members:
            lines += ["No recipes yet.", ""]
        for recipe in members:
            lines += _recipe_entry(recipe, readmes[recipe.name], root, "###")
    return "\n".join(lines).rstrip("\n") + "\n"


def render_category(
    category: Category, members: Sequence[Recipe], readmes: Mapping[str, RecipeReadme | None], folder: Path
) -> str:
    lines = [f"# {category.title}", "", category.description, "", REGEN_NOTE, ""]
    for recipe in members:
        lines += _recipe_entry(recipe, readmes[recipe.name], folder, "##")
    return "\n".join(lines).rstrip("\n") + "\n"


def _spec_link(spec: str, repo_root: Path, from_dir: Path) -> str:
    file_part, _, anchor = spec.partition("#")
    link = _relative_link(repo_root / file_part, from_dir)
    return f"{link}#{anchor}" if anchor else link


def render_feature_guide(catalog: Catalog, recipes: Sequence[Recipe], root: Path) -> str:
    guide_dir = feature_guide_path(root).parent
    repo_root = root.parent.parent
    documents = {recipe.name: recipe_documents(recipe) for recipe in recipes}
    lines = ["# Feature Guide", "", f"{REGEN_NOTE} Capabilities and groups come from `{CATALOG_NAME}`.", ""]
    unmatched: list[str] = []
    for group in catalog.guide:
        lines += [f"## {group.name}", ""]
        for capability in group.capabilities:
            matches = sorted(
                (recipe for recipe in recipes if capability_matches(capability, recipe.name, documents[recipe.name])),
                key=lambda recipe: recipe.name,
            )
            spec_link = _spec_link(capability.spec, repo_root, guide_dir)
            lines += [
                f"### {capability.name}",
                "",
                capability.summary,
                "",
                f"Spec: [{capability.spec}]({spec_link})",
                "",
            ]
            if matches:
                links = ", ".join(f"[{recipe.name}]({_relative_link(recipe.path, guide_dir)}/)" for recipe in matches)
                lines += [f"Recipes: {links}", ""]
            else:
                unmatched.append(f"- {capability.name} ({group.name})")
    lines += ["## No recipe yet", ""]
    lines += unmatched or ["Every capability has a recipe."]
    return "\n".join(lines).rstrip("\n") + "\n"


def render_documents(catalog: Catalog, recipes: Sequence[Recipe], root: Path = RECIPES_ROOT) -> dict[Path, str]:
    readmes = {recipe.name: read_readme(recipe) for recipe in recipes}
    documents = {root / README_NAME: render_index(catalog, recipes, readmes, root)}
    for category in catalog.categories:
        members = _members(category, recipes)
        if members:
            documents[root / category.key / README_NAME] = render_category(
                category, members, readmes, root / category.key
            )
    documents[feature_guide_path(root)] = render_feature_guide(catalog, recipes, root)
    return documents


def stale_category_readmes(documents: Mapping[Path, str], root: Path = RECIPES_ROOT) -> list[Path]:
    folders = sorted(path for path in root.iterdir() if path.is_dir()) if root.is_dir() else []
    return [
        folder / README_NAME
        for folder in folders
        if (folder / README_NAME).is_file() and folder / README_NAME not in documents
    ]


def document_problems(documents: Mapping[Path, str], root: Path = RECIPES_ROOT) -> list[str]:
    problems = []
    for path, text in documents.items():
        if not path.is_file():
            problems.append(f"Generated document is missing: {path}")
        elif path.read_text(encoding="utf-8") != text:
            problems.append(f"Generated document is out of date: {path}")
    problems += [
        f"Generated document is no longer generated: {path}" for path in stale_category_readmes(documents, root)
    ]
    return problems


def write_documents(documents: Mapping[Path, str], root: Path = RECIPES_ROOT) -> None:
    for path in stale_category_readmes(documents, root):
        path.unlink()
    for path, text in documents.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
